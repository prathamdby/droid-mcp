/**
 * Embeds `src/skill/droid` into `src/generated/skill.ts`.
 *
 * The skill ships inside the server, so a client that reads
 * `skill://droid/SKILL.md` gets what the repository contains, without a
 * filesystem dependency at runtime. Run `pnpm codegen` to write the file,
 * `pnpm codegen:check` to fail on drift.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join, relative, sep } from "node:path"

const ROOT = "src/skill/droid"
const OUTPUT = "src/generated/skill.ts"

const walk = (directory: string): ReadonlyArray<string> =>
  readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name)

    return entry.isDirectory() ? walk(path) : [path]
  })

const paths = walk(ROOT).sort()

const files = paths.map((path) => [
  relative(ROOT, path).split(sep).join("/"),
  readFileSync(path, "utf8"),
])

const skillMd = files.find(([path]) => path === "SKILL.md")

if (skillMd === undefined) throw new Error("skill: " + ROOT + "/SKILL.md is missing")

const identifier = (path: string): string =>
  path === "SKILL.md"
    ? "skillMd"
    : path
        .replace(/^references\//, "")
        .replace(/\.md$/, "")
        .replace(/[^a-zA-Z0-9]+(.)/g, (_, next: string) => next.toUpperCase())

/**
 * A JS string literal in the quote style the formatter prefers: double quotes
 * unless the text itself holds double quotes and no single quotes.
 */
const quote = (text: string): string => {
  const double = JSON.stringify(text)

  if (!text.includes('"') || text.includes("'")) return double

  return "'" + double.slice(1, -1).replaceAll('\\"', '"').replaceAll("'", "\\'") + "'"
}

const linesOf = (text: string): string =>
  text
    .split("\n")
    .map((line) => "  " + quote(line))
    .join(",\n")

const render = (): string => {
  const declarations = files
    .map(([path, text]) => `const ${identifier(path)} = [\n${linesOf(text)},\n].join("\\n")`)
    .join("\n\n")

  const record = files.map(([path]) => `  ${JSON.stringify(path)}: ${identifier(path)},`).join("\n")

  return `/**
 * Generated by \`scripts/embed-skill.ts\`. Do not edit.
 *
 * The droid skill, embedded so the server can serve it without reading the
 * filesystem at runtime.
 */

/** The skill root, as the URI prefix clients see. */
export const SKILL_URI = "skill://droid/SKILL.md"

${declarations}

export const SKILL_MD = skillMd

/** Every skill file, keyed by its path relative to the skill root. */
export const SKILL_FILES = {
${record}
} as const satisfies Readonly<Record<string, string>>
`
}

const file = render()
const check = process.argv.includes("--check")

if (check) {
  const existing = (() => {
    try {
      return readFileSync(OUTPUT, "utf8")
    } catch {
      return ""
    }
  })()

  if (existing !== file) {
    process.stderr.write("skill: " + OUTPUT + " is out of date; run pnpm codegen\n")
    process.exit(1)
  }

  process.stdout.write("skill: " + OUTPUT + " is current (" + String(files.length) + " files)\n")
} else {
  writeFileSync(OUTPUT, file)
  process.stdout.write("skill: wrote " + OUTPUT + " (" + String(files.length) + " files)\n")
}
